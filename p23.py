# Empty dictionary
dict1 = {}
# Dictionary with values
dict2 = {'name': 'Alice', 'age': 25}
# Dictionary using dict() constructor
dict3 = dict([('x', 1), ('y', 2)])
# Dictionary with mixed keys
dict4 = {1: 'One', 'Two': 2}
print("Empty dictionary:", dict1)
print("With values:", dict2)
print("Using dict():", dict3)
print("Mixed keys:", dict4)